const translations: Record<Locale, Record<string, string>> = { zh, en };

const I18nContext = createContext<I18nValue>({
  t: (key, values) => interpolate(key, values),
  rt: (text) => text
});

export function I18nProvider({ language, children }: { language: UiLanguage; children: ReactNode }) {
  const locale = resolveLocale(language);
  const value = useMemo<I18nValue>(() => {
    return {
      t: (key, values) => interpolate(translations[locale][key] ?? key, values),
      rt: (text) => runtimeText[locale][text] ?? text
    };
  }, [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useT() {
  return useContext(I18nContext).t;
}

export function useRuntimeText() {
  return useContext(I18nContext).rt;
}

function resolveLocale(language: UiLanguage): Locale {
  if (language === "en") {
    return "en";
  }
  return "zh";
}

function interpolate(text: string, values?: Values): string {
  if (!values) {
    return text;
  }
  return text.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match));
}
